#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

echo "Configuring OSMV C++20 (Release)..."
cmake -B linux/build -G Ninja -DCMAKE_BUILD_TYPE=Release

echo "Building OSMV Daemon + GUI..."
cmake --build linux/build -j"$(nproc)"

echo "Running unit tests..."
ctest --test-dir linux/build --output-on-failure

cp -f linux/build/osmv ./osmv
cp -f linux/build/osmv-gui ./osmv-gui
chmod +x ./osmv ./osmv-gui

# Install user-local desktop entry + icon so Wayland compositors resolve app_id icon
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
ICON_DIR="$DATA_HOME/icons/hicolor/96x96/apps"
APP_DIR="$DATA_HOME/applications"
if mkdir -p "$ICON_DIR" "$APP_DIR" 2>/dev/null; then
    cp -f linux/io.github.streammusicviewer.OSMV.png "$ICON_DIR/io.github.streammusicviewer.OSMV.png"
    sed -e "s|^Exec=.*|Exec=\"$(pwd)/osmv-gui\"|" \
        -e "s|^Icon=.*|Icon=$ICON_DIR/io.github.streammusicviewer.OSMV.png|" \
        linux/io.github.streammusicviewer.OSMV.desktop > "$APP_DIR/io.github.streammusicviewer.OSMV.desktop"
    printf '\n# Auto-generated by OSMV\n' >> "$APP_DIR/io.github.streammusicviewer.OSMV.desktop"
    command -v gtk-update-icon-cache >/dev/null 2>&1 && gtk-update-icon-cache -f -t "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true
    command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$APP_DIR" >/dev/null 2>&1 || true
    command -v kbuildsycoca6 >/dev/null 2>&1 && kbuildsycoca6 >/dev/null 2>&1 || true
fi

echo ""
echo "Done! ./osmv (daemon) and ./osmv-gui are ready."
echo "Required system packages (Arch / Ubuntu):"
echo "  Arch:   sudo pacman -S cmake ninja gcc pkgconf dbus curl glfw libgl"
echo "  Ubuntu: sudo apt install cmake ninja-build g++ pkg-config libdbus-1-dev libcurl4-openssl-dev libglfw3-dev libgl-dev"
echo "  Ubuntu 24.04 Wayland app_id deps (to auto-build GLFW 3.4): sudo apt install libwayland-dev libwayland-bin libxkbcommon-dev"

